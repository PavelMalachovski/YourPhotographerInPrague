#!/usr/bin/env bash
set -euo pipefail

echo "============================================================================="
echo "Creates k8s cluster using kubespray with a master node and 2 worker nodes"
echo "============================================================================="

helpFunction()
{
   echo ""
   echo "Usage: $0 masternode_public_ip workernode_public_ip workernode2_public_ip"
   echo "Expects terraform/YPIP/development/key.pem written by terraform apply."
   exit 1
}

export ANSIBLE_TIMEOUT=60

# Pinned release: reproducible builds and no surprise upstream changes.
# v2.26.0 is the last release that ships contrib/inventory_builder.
KUBESPRAY_VERSION="${KUBESPRAY_VERSION:-v2.26.0}"

MASTERNODE_PUBLIC_IP="${1:-}"
WORKERNODE_PUBLIC_IP="${2:-}"
WORKERNODE2_PUBLIC_IP="${3:-}"

MASTERNODE_PUBLIC_IP="${MASTERNODE_PUBLIC_IP//\"}"
WORKERNODE_PUBLIC_IP="${WORKERNODE_PUBLIC_IP//\"}"
WORKERNODE2_PUBLIC_IP="${WORKERNODE2_PUBLIC_IP//\"}"

PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TF_DIR="${PROJECT_DIR}/terraform/YPIP/development"
CLUSTER_NAME="my_kubespray_k8s"

if [ -z "$MASTERNODE_PUBLIC_IP" ] || [ -z "$WORKERNODE_PUBLIC_IP" ] || [ -z "$WORKERNODE2_PUBLIC_IP" ]
then
   echo "Missing parameters";
   helpFunction
fi

for IP in "$MASTERNODE_PUBLIC_IP" "$WORKERNODE_PUBLIC_IP" "$WORKERNODE2_PUBLIC_IP"; do
   if [[ ! "$IP" =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}$ ]]; then
      echo "Invalid IP address: $IP" >&2
      exit 1
   fi
done

echo "============================================================================="
echo "Loading SSH key generated by terraform"
echo "============================================================================="
mkdir -p ~/.ssh && chmod 700 ~/.ssh
SSH_KEY=~/.ssh/ypip_k8s_key
install -m 600 "${TF_DIR}/key.pem" "${SSH_KEY}"
rm -f "${TF_DIR}/key.pem"
# Remove the key when the script exits, even on failure.
trap 'rm -f "${SSH_KEY}"; ssh-agent -k >/dev/null 2>&1 || true' EXIT
eval "$(ssh-agent -s)" >/dev/null
ssh-add "${SSH_KEY}"

# Fresh instances have unknown host keys: trust them on first use only
# (accept-new), instead of disabling verification entirely (StrictHostKeyChecking=no).
SSH_OPTS=(-o StrictHostKeyChecking=accept-new -o UserKnownHostsFile="${HOME}/.ssh/known_hosts_ypip" -i "${SSH_KEY}")

echo "============================================================================="
echo "Grabbing kubespray ${KUBESPRAY_VERSION} from git"
echo "============================================================================="
cd "${TF_DIR}"
rm -rf kubespray
git clone --depth 1 --branch "${KUBESPRAY_VERSION}" https://github.com/kubernetes-sigs/kubespray.git
cd kubespray

echo "============================================================================="
echo "Installing kubespray requirements"
echo "============================================================================="
python3 -m venv .venv
# shellcheck disable=SC1091
source .venv/bin/activate
pip install --quiet -r requirements.txt

echo "============================================================================="
echo "Copy inventory/sample to our cluster config folder"
echo "============================================================================="
cp -rfp inventory/sample "inventory/${CLUSTER_NAME}"

declare -a ADDRESSES=("${MASTERNODE_PUBLIC_IP}" "${WORKERNODE_PUBLIC_IP}" "${WORKERNODE2_PUBLIC_IP}")
for IP in "${ADDRESSES[@]}"; do
    echo "===================== apt update for: ${IP} =========================="
    ssh "${SSH_OPTS[@]}" "ubuntu@${IP}" -- "sudo apt-get update -y && sudo DEBIAN_FRONTEND=noninteractive apt-get upgrade -y"
done

CONFIG_FILE="inventory/${CLUSTER_NAME}/hosts.yaml" python3 contrib/inventory_builder/inventory.py "${ADDRESSES[@]}"
sed -i 's/^[^#]* ip/#&/' "inventory/${CLUSTER_NAME}/hosts.yaml"  # comment ip lines

# Cluster add-ons needed by the app (k8s/) and an admin kubeconfig that
# points at the master's public IP (written to inventory/<cluster>/artifacts).
cat > "inventory/${CLUSTER_NAME}/ypip-extra-vars.yaml" <<VARS
local_path_provisioner_enabled: true
local_path_provisioner_is_default_storageclass: "true"
ingress_nginx_enabled: true
cert_manager_enabled: true
kubeconfig_localhost: true
kubeconfig_localhost_ansible_host: true
supplementary_addresses_in_ssl_keys: ["${MASTERNODE_PUBLIC_IP}"]
VARS

echo "============================================================================="
echo "Run kubespray playbook"
echo "============================================================================="
# No -vvv: maximum verbosity dumps variables (tokens, certs) into CI logs.
ANSIBLE_SSH_ARGS="-o StrictHostKeyChecking=accept-new -o UserKnownHostsFile=${HOME}/.ssh/known_hosts_ypip" \
ansible-playbook -i "inventory/${CLUSTER_NAME}/hosts.yaml" cluster.yml \
  --private-key "${SSH_KEY}" \
  -e 'ansible_python_interpreter=/usr/bin/python3 ansible_user=ubuntu' \
  -e "@inventory/${CLUSTER_NAME}/ypip-extra-vars.yaml" \
  -b --become-user=root --flush-cache

KUBECONFIG_OUT="${TF_DIR}/kubespray/inventory/${CLUSTER_NAME}/artifacts/admin.conf"
chmod 600 "${KUBECONFIG_OUT}"
echo "Admin kubeconfig: ${KUBECONFIG_OUT}"
